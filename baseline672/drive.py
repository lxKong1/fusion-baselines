"""Load one trusted policy checkpoint and actually drive in MetaDrive (no REF)."""
import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import random

import numpy as np


MODULES = {"fusion": "fusion_policy", "safe-bc": "safe_bc", "cpq": "cpq_policy"}


def build_environment_config(args):
    from metadrive.manager.traffic_manager import TrafficMode

    return {
        "use_render": args.render,
        "offscreen_render": True,
        "window_size": (1100, 760),
        # MetaDrive's map manager allocates valid seeds from start_seed through
        # start_seed + environment_num - 1. Each rollout episode deliberately
        # uses the next seed, so reserve the whole requested range up front.
        "environment_num": args.episodes,
        "start_seed": args.seed,
        "frame_stack": 3,
        "safe_rl_env": False,
        "random_traffic": False,
        "accident_prob": 0,
        "distance": 20,
        "vehicle_config": {
            "lidar": {"num_lasers": 240, "distance": 50, "num_others": 4}
        },
        "map_config": {"type": "block_sequence", "config": args.scene},
        "traffic_density": args.traffic_density,
        "traffic_mode": TrafficMode.Trigger,
        "horizon": args.horizon - 1,
        "fusion_bev_observation": args.algo == "fusion",
    }


def drive_episode(env, policy, seed, horizon, render=False):
    obs = env.reset(force_seed=seed)
    policy.reset()
    total_r, total_c = 0., 0.
    for step in range(1, horizon + 1):
        a = np.asarray(policy.act(obs), dtype=np.float32)
        if a.shape != (2,) or not np.isfinite(a).all() or np.max(np.abs(a)) > 1.00001:
            raise ValueError(f"invalid steering/throttle action at {step}: {a}")
        a = np.clip(a, -1., 1.)
        obs, reward, done, info = env.step(a)
        actual = np.asarray(info["raw_action"], dtype=np.float32)
        if actual.shape != (2,) or not np.allclose(actual, a, atol=1e-6, rtol=0):
            raise RuntimeError("simulator did not execute the loaded policy's action")
        if getattr(getattr(env, "vehicle", None), "expert_takeover", False):
            raise RuntimeError("unexpected expert takeover in baseline rollout")
        cost = float(info["cost"])
        policy.observe(actual, float(reward), cost)
        total_r += float(reward)
        total_c += cost
        if render:
            env.render(mode="human")
        if done or cost > 0 or step == horizon:
            crash = any(info.get(k, False) for k in ("crash_vehicle", "crash_building", "crash_object", "crash"))
            outcome = ("collision" if crash else "off_road" if info.get("out_of_road") else
                       "safety_event" if cost else "success" if info.get("arrive_dest") else
                       "timeout" if info.get("max_step") or step == horizon else "other_terminal")
            return dict(seed=seed, steps=step, outcome=outcome, reward=total_r, cost=total_c)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--algo", choices=MODULES, required=True)
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--device", default="cpu")
    p.add_argument("--scene", choices=list("SORTX"), default="O")
    p.add_argument("--seed", type=int, default=940000)
    p.add_argument("--horizon", type=int, default=1000)
    p.add_argument("--traffic-density", type=float, default=.2)
    p.add_argument("--episodes", type=int, default=1)
    p.add_argument("--render", action="store_true", help="Open the native MetaDrive window")
    args = p.parse_args()
    if not (2 <= args.horizon <= 1000 and args.episodes > 0 and 0 <= args.traffic_density <= 1):
        p.error("expected horizon in [2,1000], positive episodes and density in [0,1]")
    if not args.checkpoint.is_file():
        p.error("checkpoint not found")
    os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
    os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
    from panda3d.core import loadPrcFileData
    # TinyDisplay's 84x84 texture warnings concern the unused Panda display;
    # policy BEV is generated by the independent SDL semantic renderer.
    headless = "" if args.render else ("load-display p3tinydisplay\n"
                                       "notify-level-display fatal\nnotify-level-tinydisplay fatal\n")
    loadPrcFileData("", headless + "model-cache-dir\naudio-library-name null")
    import torch
    from fusion.envs.envs import State_TopDownMetaDriveEnv
    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    torch.set_num_threads(1)
    module = importlib.import_module("baseline672." + MODULES[args.algo])
    policy = module.load_policy(args.checkpoint, args.device)
    config = build_environment_config(args)
    digest = hashlib.sha256(args.checkpoint.read_bytes()).hexdigest()
    env = State_TopDownMetaDriveEnv(config)
    try:
        for i in range(args.episodes):
            result = drive_episode(env, policy, args.seed + i, args.horizon, args.render)
            result.update(algo=args.algo, checkpoint_sha256=digest, scene=args.scene,
                          traffic_density=args.traffic_density)
            print(json.dumps(result, allow_nan=False), flush=True)
    finally:
        env.close()


if __name__ == "__main__":
    main()
